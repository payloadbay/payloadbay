import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { withFixtures } from "../../scripts/tests/fixtures.ts";
import { Client } from "pg";

test("RI07 migration CLI applies explicit history, stays idempotent and provisions narrow runtime logins", async () => {
	await withFixtures(async (fixture) => {
		const run = (env: NodeJS.ProcessEnv, args = ["--directory", "tests/fixtures/schema-history"]) => spawnSync(process.execPath, ["--import", "tsx", "scripts/migrate.ts", ...args], { env: { PATH: process.env.PATH, ...env }, encoding: "utf8", timeout: 20000 });

		const missing = run({});
		assert.equal(missing.status, 1);
		assert.match(missing.stderr, /MIGRATION_DATABASE_URL is required/);
		const first = run({ MIGRATION_DATABASE_URL: fixture.databaseUrl });
		assert.equal(first.error, undefined);
		assert.equal(first.status, 0, first.stderr);
		assert.match(first.stdout, /Payload Bay migrations complete/);
		const db = new Client({ connectionString: fixture.databaseUrl });
		await db.connect();
		try {
			const before = (await db.query("SELECT name,digest FROM payloadbay.schema_migration ORDER BY name")).rows;
			assert.ok(before.length);
			const repeated = run({ DATABASE_URL: fixture.databaseUrl });
			assert.equal(repeated.status, 0, repeated.stderr);
			assert.deepEqual((await db.query("SELECT name,digest FROM payloadbay.schema_migration ORDER BY name")).rows, before);
			const malformed = run({ DATABASE_URL: fixture.databaseUrl, PAYLOADBAY_APP_DATABASE_PASSWORD: "invalid" });
			assert.equal(malformed.status, 1);
			assert.match(malformed.stderr, /Payload Bay migration failed/);
			assert.doesNotMatch(malformed.stderr, /invalid|fixture-only/);
			const provisioned = run({ MIGRATION_DATABASE_URL: fixture.databaseUrl, PAYLOADBAY_APP_DATABASE_PASSWORD: "synthetic-cli-app-password-32-characters", PAYLOADBAY_WORKER_DATABASE_PASSWORD: "synthetic-cli-worker-password-32-characters" });
			assert.equal(provisioned.status, 0, provisioned.stderr);
			const roles = (await db.query("SELECT rolname,rolsuper,rolcreatedb,rolcreaterole FROM pg_roles WHERE rolname IN ('payloadbay_web','payloadbay_jobs') ORDER BY rolname")).rows;
			assert.deepEqual(roles, [
				{
					rolname: "payloadbay_jobs",
					rolsuper: false,
					rolcreatedb: false,
					rolcreaterole: false,
				},
				{
					rolname: "payloadbay_web",
					rolsuper: false,
					rolcreatedb: false,
					rolcreaterole: false,
				},
			]);
			const absent = run({ DATABASE_URL: fixture.databaseUrl }, ["--directory", "tests/fixtures/absent-release-sql"]);
			assert.equal(absent.status, 1);
			assert.match(absent.stderr, /Payload Bay migration failed/);
		} finally {
			await db.end();
		}
	});
});

test("CV09 migration policy CLI rejects branch generation and staged history while permitting master CI", async () => {
	const { mkdtemp, mkdir, writeFile, rm } = await import("node:fs/promises");
	const { resolve, join } = await import("node:path");
	const { tmpdir } = await import("node:os");
	const { execFileSync } = await import("node:child_process");
	const directory = await mkdtemp(join(tmpdir(), "pab-policy-git-"));
	try {
		execFileSync("git", ["init", directory], { stdio: "ignore" });

		const run = (mode: string, approved = false) =>
			spawnSync(process.execPath, ["--import", "tsx", "scripts/database/migration-policy.ts", mode], {
				encoding: "utf8",
				timeout: 5000,
				env: {
					PATH: process.env.PATH,
					GIT_DIR: join(directory, ".git"),
					GIT_WORK_TREE: directory,
					GITHUB_ACTIONS: String(approved),
					GITHUB_REF: approved ? "refs/heads/master" : "refs/pull/13/head",
					PAYLOADBAY_MIGRATION_WORKFLOW: String(approved),
				},
			});

		const blocked = run("generate");
		assert.equal(blocked.status, 1);
		assert.match(blocked.stderr, /generated by the master CI/);
		assert.equal(run("generate", true).status, 0);
		assert.equal(run("staged").status, 0);
		await mkdir(join(directory, "packages/domain/drizzle"), { recursive: true });
		await writeFile(join(directory, "packages/domain/drizzle/0000_policy_fixture.sql"), "-- synthetic policy fixture, never release SQL");
		execFileSync("git", ["-C", directory, "add", "packages/domain/drizzle"], { stdio: "ignore" });
		const staged = run("staged");
		assert.equal(staged.status, 1);
		assert.match(staged.stderr, /Feature branches must not commit/);
		assert.equal(run("staged", true).status, 0);
		const invalid = run("unknown");
		assert.equal(invalid.status, 1);
		assert.match(invalid.stderr, /Use migration-policy/);
		assert.equal(resolve(directory).startsWith(tmpdir()), true);
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});
