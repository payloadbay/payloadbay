import { execFileSync } from "node:child_process";

export function canGenerateReleaseMigrations(environment: Record<string, string | undefined>) {
	return environment.GITHUB_ACTIONS === "true" && environment.GITHUB_REF === "refs/heads/master" && environment.PAYLOADBAY_MIGRATION_WORKFLOW === "true";
}

export function migrationPolicyViolations(files: readonly string[], environment: Record<string, string | undefined>) {
	return canGenerateReleaseMigrations(environment) ? [] : files.filter((file) => /^packages\/domain\/drizzle\/(?:\d{4}_.+\.sql|meta\/(?:\d{4}_snapshot|_journal)\.json)$/.test(file.replaceAll("\\", "/")));
}

if (import.meta.main) {
	const mode = process.argv[2];
	if (mode === "generate") {
		if (!canGenerateReleaseMigrations(process.env)) {
			console.error("Release migrations are generated by the master CI workflow. Commit schema source; use db:push for development.");
			process.exitCode = 1;
		}
	} else if (mode === "staged") {
		const files = execFileSync("git", ["diff", "--cached", "--name-only", "--diff-filter=ACMR", "--", "packages/domain/drizzle"], { encoding: "utf8" }).trim().split("\n");
		if (migrationPolicyViolations(files, process.env).length) {
			console.error("Feature branches must not commit generated release migrations. Master CI owns generation.");
			process.exitCode = 1;
		}
	} else throw Error("Use migration-policy.ts generate|staged");
}
